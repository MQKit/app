//! Engines downloaded on demand (contract section 3): pinned in `engines.toml`
//! by size and SHA-256, downloaded over HTTPS, checked, then installed into
//! `%LOCALAPPDATA%\com.mqkit.app\engines\<name>\<version>\`.
//!
//! Install modes (`extract`):
//! - `files`  (default) only the listed files, flat (FFmpeg);
//! - `all`    the whole zip (portable Python);
//! - `wheels` each Python wheel unzipped into `site-packages` (pdf2docx and its deps);
//! - `msi`    an administrative install (`msiexec /a`): unpacks an MSI without
//!   installing anything or asking for admin rights (LibreOffice);
//! - `file`   the download is the file itself, kept as `files[0]` (an AI model).

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};

#[derive(Deserialize, Serialize, Clone, Debug)]
pub struct Wheel {
    pub name: String,
    pub url: String,
    pub size: u64,
    pub sha256: String,
    #[serde(default)]
    pub license: String,
    /// Paths inside the wheel that are not extracted (not needed, e.g. OpenCV's video DLL).
    #[serde(default)]
    pub skip: Vec<String>,
}

#[derive(Deserialize, Serialize, Clone, Debug)]
pub struct Engine {
    pub version: String,
    #[serde(default)]
    pub url: String,
    #[serde(default)]
    pub size: u64,
    #[serde(default)]
    pub sha256: String,
    #[serde(default)]
    pub license: String,
    #[serde(default)]
    pub source: String,
    #[serde(default)]
    pub files: Vec<String>,
    #[serde(default = "files_mode")]
    pub extract: String,
    #[serde(default)]
    pub requires: Vec<String>,
    #[serde(default)]
    pub wheels: Vec<Wheel>,
    /// Whether MQKit keeps a copy in github.com/MQKit/engines to fall back on.
    #[serde(default = "yes")]
    pub mirror: bool,
    /// Paths removed after extraction (`*` matches one path segment)…
    #[serde(default)]
    pub prune: Vec<String>,
    /// …except these.
    #[serde(default)]
    pub keep: Vec<String>,
}

fn yes() -> bool {
    true
}

fn files_mode() -> String {
    "files".into()
}

impl Engine {
    fn download_bytes(&self) -> u64 {
        self.size + self.wheels.iter().map(|w| w.size).sum::<u64>()
    }
}

/// `engines.toml` plus `engines.python.toml` (generated by scripts/gen-python-engines.py).
pub fn catalog() -> BTreeMap<String, Engine> {
    // Development only: a test catalog (served from 127.0.0.1).
    if cfg!(debug_assertions) {
        if let Some(t) = std::env::var_os("CONVERTOR_ENGINES_TOML") {
            let text = std::fs::read_to_string(t).unwrap_or_default();
            return toml::from_str(&text).unwrap_or_default();
        }
    }
    let mut all = BTreeMap::new();
    for name in ["engines.toml", "engines.python.toml"] {
        #[cfg_attr(not(debug_assertions), allow(unused_mut))]
        let mut text = std::fs::read_to_string(crate::paths::resources().join(name)).unwrap_or_default();
        // Development only: the catalog next to the sources (never compiled into a release).
        #[cfg(debug_assertions)]
        if text.is_empty() {
            text = std::fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join(name)).unwrap_or_default();
        }
        match toml::from_str::<BTreeMap<String, Engine>>(&text) {
            Ok(m) => all.extend(m),
            Err(e) => applog!("{name}: {e}"),
        }
    }
    all
}

fn base_name(p: &str) -> &str {
    p.rsplit(['/', '\\']).next().unwrap_or(p)
}

/// What must exist in the version folder for the engine to count as installed.
fn expected(e: &Engine) -> Vec<String> {
    if e.extract == "files" {
        e.files.iter().filter(|f| f.to_ascii_lowercase().ends_with(".exe")).map(|f| base_name(f).to_string()).collect()
    } else {
        e.files.clone()
    }
}

/// The folder of the pinned version, if it is complete (and its requirements too).
pub fn installed_dir(name: &str) -> Option<PathBuf> {
    let cat = catalog();
    installed_in(name, &cat)
}

fn installed_in(name: &str, cat: &BTreeMap<String, Engine>) -> Option<PathBuf> {
    let e = cat.get(name)?;
    let d = crate::paths::engines_dir().join(name).join(&e.version);
    let complete = expected(e).iter().all(|x| d.join(x).exists()) && e.requires.iter().all(|r| installed_in(r, cat).is_some());
    complete.then_some(d)
}

/// The extraction mode of an engine (`wheels` engines go into CONVERTOR_PYPATH).
pub fn mode(name: &str) -> Option<String> {
    catalog().get(name).map(|e| e.extract.clone())
}

/// `name` and everything it requires.
pub fn with_requirements(name: &str) -> Vec<String> {
    let cat = catalog();
    let mut out = Vec::new();
    fn walk(n: &str, cat: &BTreeMap<String, Engine>, out: &mut Vec<String>) {
        if let Some(e) = cat.get(n) {
            for r in &e.requires {
                walk(r, cat, out);
            }
        }
        if !out.iter().any(|x| x == n) {
            out.push(n.to_string());
        }
    }
    walk(name, &cat, &mut out);
    out
}

pub fn status(name: &str) -> &'static str {
    if installed_dir(name).is_some() {
        "installed"
    } else if catalog().contains_key(name) {
        "downloadable"
    } else {
        "unavailable"
    }
}

/// Engines to download for `name`, requirements first, only those missing.
fn plan(name: &str, cat: &BTreeMap<String, Engine>, out: &mut Vec<String>) {
    if let Some(e) = cat.get(name) {
        for r in &e.requires {
            plan(r, cat, out);
        }
        let d = crate::paths::engines_dir().join(name).join(&e.version);
        let own_complete = expected(e).iter().all(|x| d.join(x).exists());
        if !own_complete && !out.iter().any(|x| x == name) {
            out.push(name.to_string());
        }
    }
}

fn dir_size(p: &Path) -> u64 {
    std::fs::read_dir(p)
        .map(|rd| rd.flatten().map(|e| e.metadata().map(|m| if m.is_dir() { dir_size(&e.path()) } else { m.len() }).unwrap_or(0)).sum())
        .unwrap_or(0)
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Info {
    name: String,
    version: String,
    /// What a download costs now, requirements included.
    download_bytes: u64,
    license: String,
    source: String,
    status: &'static str,
    installed_bytes: u64,
    downloading: bool,
    requires: Vec<String>,
}

pub fn list() -> Vec<Info> {
    let active = ACTIVE.lock().unwrap().clone();
    let cat = catalog();
    cat.iter()
        .map(|(name, e)| {
            let mut todo = Vec::new();
            plan(name, &cat, &mut todo);
            let bytes: u64 = if todo.is_empty() { e.download_bytes() } else { todo.iter().filter_map(|n| cat.get(n)).map(Engine::download_bytes).sum() };
            let installed = installed_in(name, &cat);
            Info {
                installed_bytes: installed.as_ref().map(|d| dir_size(d)).unwrap_or(0),
                downloading: active.contains_key(name),
                status: if installed.is_some() { "installed" } else { "downloadable" },
                name: name.clone(),
                version: e.version.clone(),
                download_bytes: bytes,
                license: e.license.clone(),
                source: e.source.clone(),
                requires: e.requires.clone(),
            }
        })
        .collect()
}

static ACTIVE: Mutex<BTreeMap<String, Arc<AtomicBool>>> = Mutex::new(BTreeMap::new());

pub fn cancel(name: &str) {
    if let Some(c) = ACTIVE.lock().unwrap().get(name) {
        c.store(true, Ordering::Relaxed);
    }
}

/// Deletes every downloaded version of an engine.
pub fn remove(name: &str) -> Result<(), String> {
    // Only an engine of the catalog: the name becomes a folder to delete.
    if !catalog().contains_key(name) {
        return Err("unknown_engine".into());
    }
    if !ACTIVE.lock().unwrap().is_empty() {
        return Err("busy".into());
    }
    let d = crate::paths::engines_dir().join(name);
    if d.exists() {
        crate::paths::remove_tree(&d);
    }
    Ok(())
}

#[cfg(windows)]
pub(crate) fn free_space(p: &Path) -> Option<u64> {
    use std::os::windows::ffi::OsStrExt;
    let w: Vec<u16> = p.as_os_str().encode_wide().chain(Some(0)).collect();
    let mut free = 0u64;
    unsafe {
        windows::Win32::Storage::FileSystem::GetDiskFreeSpaceExW(windows::core::PCWSTR(w.as_ptr()), Some(&mut free), None, None).ok()?;
    }
    Some(free)
}

#[cfg(not(windows))]
pub(crate) fn free_space(_: &Path) -> Option<u64> {
    None
}

fn allowed_url(url: &str) -> bool {
    url.starts_with("https://") || (cfg!(debug_assertions) && url.starts_with("http://127.0.0.1"))
}

/// Downloads, verifies and installs `name` and whatever it requires.
/// `progress(done, total)` covers all of it. Errors are codes: `unknown_engine`,
/// `busy`, `disk_full`, `network`, `hash_mismatch`, `bad_archive`, `cancelled`,
/// `permission_denied`, `install_failed`.
/// One install at a time: engines share requirements (four AI models need ONNX Runtime),
/// and two installs of the same one would undo each other's files.
static INSTALLING: Mutex<()> = Mutex::new(());

pub fn download(name: &str, progress: impl Fn(u64, u64)) -> Result<PathBuf, String> {
    let cat = catalog();
    if !cat.contains_key(name) {
        return Err("unknown_engine".into());
    }
    let flag = Arc::new(AtomicBool::new(false));
    {
        let mut a = ACTIVE.lock().unwrap();
        if a.contains_key(name) {
            return Err("busy".into());
        }
        a.insert(name.to_string(), flag.clone());
    }
    // Waits for another install to finish, then plans: what it installed is not redone.
    let _one_at_a_time = INSTALLING.lock().unwrap_or_else(|e| e.into_inner());
    let mut todo = Vec::new();
    plan(name, &cat, &mut todo);
    if todo.is_empty() {
        ACTIVE.lock().unwrap().remove(name);
        return installed_dir(name).ok_or_else(|| "install_failed".into());
    }
    let total: u64 = todo.iter().filter_map(|n| cat.get(n)).map(Engine::download_bytes).sum();
    let mut offset = 0u64;
    let mut res = Ok(());
    for n in &todo {
        let e = &cat[n];
        res = install(n, e, &flag, &|d| progress(offset + d, total));
        crate::paths::remove_tree(&crate::paths::engines_dir().join(n).join(".download"));
        if res.is_err() {
            break;
        }
        offset += e.download_bytes();
    }
    ACTIVE.lock().unwrap().remove(name);
    res?;
    progress(total, total);
    installed_dir(name).ok_or_else(|| "install_failed".into())
}

/// One verified download to `dest`. `progress(bytes of this file)`.
/// A broken connection resumes where it stopped (HTTP Range), up to 4 times.
/// MQKit's own copy of every engine file: a release per engine and version
/// (`<name>-<version>`) in github.com/MQKit/engines, each asset named as at its source.
const MIRROR: &str = "https://github.com/MQKit/engines/releases/download";

/// Where the copy of `url` is kept.
fn mirror_url(name: &str, version: &str, url: &str) -> String {
    let file = url.rsplit('/').next().unwrap_or(url).split(['?', '#']).next().unwrap_or("");
    format!("{MIRROR}/{name}-{version}/{file}")
}

/// From the engine's own source; when that fails (gone, moved, changed or unreachable),
/// from MQKit's copy. Both must match the same size and SHA-256, so the copy can never
/// be anything else.
fn fetch_with_mirror(url: &str, mirror: Option<String>, size: u64, sha256: &str, dest: &Path, cancel: &AtomicBool, progress: &dyn Fn(u64)) -> Result<(), String> {
    match fetch(url, size, sha256, dest, cancel, progress) {
        Err(e) if matches!(e.as_str(), "network" | "hash_mismatch" | "unknown_engine") => {
            let Some(mirror) = mirror else { return Err(e) };
            let _ = std::fs::remove_file(dest);
            fetch(&mirror, size, sha256, dest, cancel, progress).map_err(|m| if m == "cancelled" { m } else { e })
        }
        other => other,
    }
}

fn fetch(url: &str, size: u64, sha256: &str, dest: &Path, cancel: &AtomicBool, progress: &dyn Fn(u64)) -> Result<(), String> {
    if !allowed_url(url) {
        return Err("unknown_engine".into());
    }
    // An archive already downloaded and verified (a previous attempt failed later): reuse it.
    if std::fs::metadata(dest).map(|m| m.len() == size).unwrap_or(false) {
        if let Ok(mut f) = std::fs::File::open(dest) {
            let mut h = Sha256::new();
            let mut buf = vec![0u8; 1 << 20];
            let mut ok = true;
            loop {
                match f.read(&mut buf) {
                    Ok(0) => break,
                    Ok(n) => h.update(&buf[..n]),
                    Err(_) => {
                        ok = false;
                        break;
                    }
                }
            }
            if ok {
                let hash: String = h.finalize().iter().map(|b| format!("{b:02x}")).collect();
                if hash.eq_ignore_ascii_case(sha256) {
                    progress(size);
                    return Ok(());
                }
            }
        }
    }
    // The body timeout is a total: allow at least 100 KB/s, never less than 2 minutes.
    let body_secs = (size / 100_000).max(120);
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .tls_config(crate::tls())
        .timeout_connect(Some(std::time::Duration::from_secs(20)))
        .timeout_recv_response(Some(std::time::Duration::from_secs(60)))
        .timeout_recv_body(Some(std::time::Duration::from_secs(body_secs)))
        .user_agent("MQKit-engine-downloader")
        .build()
        .into();
    let mut file = std::fs::File::create(dest).map_err(|_| "permission_denied")?;
    let mut hasher = Sha256::new();
    let mut buf = vec![0u8; 256 * 1024];
    let mut done = 0u64;
    let mut last = std::time::Instant::now();
    let mut attempts = 0;
    'outer: loop {
        attempts += 1;
        let mut req = agent.get(url);
        if done > 0 {
            req = req.header("Range", &format!("bytes={done}-"));
        }
        let mut resp = match req.call() {
            Ok(r) => r,
            Err(err) => {
                applog!("download {url}: {err}");
                if attempts < 5 && !cancel.load(Ordering::Relaxed) {
                    std::thread::sleep(std::time::Duration::from_secs(2));
                    continue;
                }
                return Err("network".into());
            }
        };
        if done > 0 && resp.status().as_u16() != 206 {
            // The server ignored the range: start over.
            done = 0;
            hasher = Sha256::new();
            file = std::fs::File::create(dest).map_err(|_| "permission_denied")?;
        }
        let mut reader = resp.body_mut().with_config().limit(size + 1).reader();
        loop {
            if cancel.load(Ordering::Relaxed) {
                return Err("cancelled".into());
            }
            let n = match reader.read(&mut buf) {
                Ok(n) => n,
                Err(err) => {
                    applog!("download {url} at {done}: {err}");
                    if attempts < 5 {
                        continue 'outer;
                    }
                    return Err("network".into());
                }
            };
            if n == 0 {
                break 'outer;
            }
            hasher.update(&buf[..n]);
            file.write_all(&buf[..n]).map_err(|err| if err.kind() == std::io::ErrorKind::StorageFull { "disk_full" } else { "permission_denied" })?;
            done += n as u64;
            if last.elapsed().as_millis() >= 150 {
                last = std::time::Instant::now();
                progress(done);
            }
        }
    }
    let hash: String = hasher.finalize().iter().map(|b| format!("{b:02x}")).collect();
    if done != size || !hash.eq_ignore_ascii_case(sha256) {
        applog!("download {url}: size {done} / {size}, sha256 {hash}");
        return Err("hash_mismatch".into());
    }
    progress(size);
    Ok(())
}

/// Unzips everything into `into` (paths that would leave it are refused), except `skip`.
fn unzip_all(archive: &Path, into: &Path, cancel: &AtomicBool) -> Result<(), String> {
    unzip_except(archive, into, cancel, &[])
}

fn unzip_except(archive: &Path, into: &Path, cancel: &AtomicBool, skip: &[String]) -> Result<(), String> {
    let f = std::fs::File::open(archive).map_err(|_| "permission_denied")?;
    let mut zip = zip::ZipArchive::new(f).map_err(|_| "bad_archive")?;
    for i in 0..zip.len() {
        if cancel.load(Ordering::Relaxed) {
            return Err("cancelled".into());
        }
        let mut entry = zip.by_index(i).map_err(|_| "bad_archive")?;
        let Some(rel) = entry.enclosed_name() else { return Err("bad_archive".into()) };
        let rel_s = rel.to_string_lossy().replace('\\', "/");
        if skip.iter().any(|x| x.eq_ignore_ascii_case(&rel_s)) {
            continue;
        }
        let target = into.join(rel);
        if entry.is_dir() {
            std::fs::create_dir_all(&target).map_err(|_| "permission_denied")?;
            continue;
        }
        if let Some(p) = target.parent() {
            std::fs::create_dir_all(p).map_err(|_| "permission_denied")?;
        }
        let mut out = std::fs::File::create(&target).map_err(|_| "permission_denied")?;
        std::io::copy(&mut entry, &mut out).map_err(|_| "bad_archive")?;
    }
    Ok(())
}

/// When the staging folder holds a single folder (`LibreOffice/…`), its content moves up.
fn flatten_single_dir(staging: &Path) {
    let entries: Vec<PathBuf> = std::fs::read_dir(staging).map(|rd| rd.flatten().map(|e| e.path()).collect()).unwrap_or_default();
    let dirs: Vec<&PathBuf> = entries.iter().filter(|p| p.is_dir()).collect();
    let files = entries.iter().filter(|p| p.is_file() && !p.extension().map(|e| e.eq_ignore_ascii_case("msi")).unwrap_or(false)).count();
    if dirs.len() == 1 && files == 0 {
        let inner = dirs[0].clone();
        let tmp = staging.with_extension("inner");
        if std::fs::rename(&inner, &tmp).is_ok() {
            if let Ok(rd) = std::fs::read_dir(&tmp) {
                for e in rd.flatten() {
                    let _ = std::fs::rename(e.path(), staging.join(e.file_name()));
                }
            }
            let _ = std::fs::remove_dir(&tmp);
        }
    }
}

fn install(name: &str, e: &Engine, cancel: &AtomicBool, progress: &dyn Fn(u64)) -> Result<(), String> {
    let base = crate::paths::engines_dir().join(name);
    let tmp = base.join(".download");
    crate::paths::remove_tree(&tmp);
    std::fs::create_dir_all(&tmp).map_err(|_| "permission_denied")?;
    // The archive plus what comes out of it (an MSI unpacks to about 3×).
    let factor = if e.extract == "msi" { 4 } else { 3 };
    if free_space(&tmp).map(|f| f < e.download_bytes() * factor + 50_000_000).unwrap_or(false) {
        return Err("disk_full".into());
    }
    let staging = tmp.join("staging");
    std::fs::create_dir_all(&staging).map_err(|_| "permission_denied")?;

    match e.extract.as_str() {
        "wheels" => {
            let site = staging.join("site-packages");
            std::fs::create_dir_all(&site).map_err(|_| "permission_denied")?;
            let mut off = 0u64;
            for (i, w) in e.wheels.iter().enumerate() {
                let f = tmp.join(format!("w{i}.whl"));
                fetch_with_mirror(&w.url, e.mirror.then(|| mirror_url(name, &e.version, &w.url)), w.size, &w.sha256, &f, cancel, &|d| progress(off + d))?;
                unzip_except(&f, &site, cancel, &w.skip)?;
                let _ = std::fs::remove_file(&f);
                off += w.size;
            }
        }
        mode => {
            let ext = if mode == "msi" { "msi" } else { "zip" };
            // Windows Installer can't open a package inside the app's data folder
            // (error 1619): an MSI waits in %TEMP%, kept there until it installs.
            let archive = if mode == "msi" {
                let d = std::env::temp_dir().join(format!("convertor-{name}-{}", e.version));
                std::fs::create_dir_all(&d).map_err(|_| "permission_denied")?;
                d.join("archive.msi")
            } else {
                tmp.join(format!("archive.{ext}"))
            };
            fetch_with_mirror(&e.url, e.mirror.then(|| mirror_url(name, &e.version, &e.url)), e.size, &e.sha256, &archive, cancel, progress)?;
            if cancel.load(Ordering::Relaxed) {
                return Err("cancelled".into());
            }
            match mode {
                "all" => unzip_all(&archive, &staging, cancel)?,
                "file" => {
                    let target = staging.join(base_name(e.files.first().map(String::as_str).unwrap_or("model.bin")));
                    std::fs::rename(&archive, &target).map_err(|_| "permission_denied")?;
                }
                "msi" => {
                    msi_admin_install(&archive, &staging)?;
                    let _ = std::fs::remove_file(staging.join("archive.msi"));
                    flatten_single_dir(&staging);
                    if let Some(d) = archive.parent() {
                        crate::paths::remove_tree(d);
                    }
                }
                _ => extract_listed(&archive, &staging, e, cancel)?,
            }
            let _ = std::fs::remove_file(&archive);
        }
    }
    let count = |p: &Path| std::fs::read_dir(p).map(|d| d.count()).unwrap_or(0);
    applog!("engine {name}: staging has {} entries before prune", count(&staging));
    if !e.prune.is_empty() {
        prune(&staging, &staging, e);
    }
    applog!("engine {name}: {} entries after prune, program/ has {}", count(&staging), count(&staging.join("program")));
    if e.extract == "wheels" {
        precompile(e, &staging.join("site-packages"));
    }
    for x in expected(e) {
        if !staging.join(&x).exists() {
            applog!("engine {name}: {x} missing after extraction");
            return Err("bad_archive".into());
        }
    }
    let _ = std::fs::write(
        staging.join("SOURCE.txt"),
        format!(
            "{name} {}\r\nDownloaded from: {}\r\nSHA-256: {}\r\nLicense: {}\r\nSource code: {}\r\n",
            e.version,
            if e.url.is_empty() { "PyPI (see engines.toml)" } else { &e.url },
            e.sha256,
            e.license,
            e.source
        ),
    );
    let final_dir = base.join(&e.version);
    if final_dir.exists() {
        crate::paths::remove_tree(&final_dir);
    }
    std::fs::rename(&staging, &final_dir).map_err(|_| "permission_denied")?;
    applog!("engine {name}: installed, {} entries in {}", count(&final_dir), final_dir.display());
    if let Ok(rd) = std::fs::read_dir(&base) {
        for d in rd.flatten() {
            let p = d.path();
            if p != final_dir && p.file_name().map(|n| n != ".download").unwrap_or(false) {
                crate::paths::remove_tree(&p);
            }
        }
    }
    Ok(())
}

fn extract_listed(archive: &Path, staging: &Path, e: &Engine, cancel: &AtomicBool) -> Result<(), String> {
    let f = std::fs::File::open(archive).map_err(|_| "permission_denied")?;
    let mut zip = zip::ZipArchive::new(f).map_err(|_| "bad_archive")?;
    let wanted: Vec<(String, String)> = e.files.iter().map(|f| (f.to_ascii_lowercase(), base_name(f).to_string())).collect();
    for i in 0..zip.len() {
        if cancel.load(Ordering::Relaxed) {
            return Err("cancelled".into());
        }
        let mut entry = zip.by_index(i).map_err(|_| "bad_archive")?;
        if entry.is_dir() {
            continue;
        }
        let entry_name = entry.name().map_err(|_| "bad_archive")?.replace('\\', "/").to_ascii_lowercase();
        let Some((_, out_name)) = wanted.iter().find(|(k, _)| entry_name.ends_with(&format!("/{k}")) || entry_name == *k) else { continue };
        let mut out = std::fs::File::create(staging.join(out_name)).map_err(|_| "permission_denied")?;
        std::io::copy(&mut entry, &mut out).map_err(|_| "bad_archive")?;
    }
    Ok(())
}

/// `msiexec /a`: unpacks the MSI's files into `target` without installing.
fn msi_admin_install(msi: &Path, target: &Path) -> Result<(), String> {
    #[cfg(windows)]
    use std::os::windows::process::CommandExt;
    let log = msi.with_extension("log");
    let mut cmd = std::process::Command::new("msiexec.exe");
    // msiexec reads a property as NAME="value": the value quoted, not the whole argument
    // (as Rust would quote it), or a folder with a space in it (a user name like
    // "Ana Maria") makes the install fail.
    cmd.arg("/a").arg(msi).arg("/qn").raw_arg(format!("TARGETDIR=\"{}\"", target.display())).arg("/L*").arg(&log);
    #[cfg(windows)]
    cmd.creation_flags(0x0800_0000);
    let status = cmd.status().map_err(|_| "install_failed")?;
    if !status.success() {
        applog!("msiexec exit {:?}; log: {}", status.code(), log.display());
        return Err("install_failed".into());
    }
    // msiexec can also end with 0 and nothing unpacked; checked by the caller.
    if std::fs::read_dir(target).map(|mut d| d.next().is_none()).unwrap_or(true) {
        applog!("msiexec unpacked nothing; log: {}", log.display());
        return Err("install_failed".into());
    }
    Ok(())
}

fn glob_match(pattern: &str, path: &str) -> bool {
    let p: Vec<&str> = pattern.split('/').collect();
    let s: Vec<&str> = path.split('/').collect();
    p.len() == s.len() && p.iter().zip(&s).all(|(a, b)| seg_match(a, b))
}

fn seg_match(p: &str, s: &str) -> bool {
    let p = p.to_ascii_lowercase();
    let s = s.to_ascii_lowercase();
    match p.split_once('*') {
        None => p == s,
        Some((a, b)) => s.len() >= a.len() + b.len() && s.starts_with(a) && s.ends_with(b),
    }
}

/// Deletes what `prune` lists, except `keep`, walking the extracted tree.
fn prune(root: &Path, dir: &Path, e: &Engine) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for entry in rd.flatten() {
        let p = entry.path();
        let rel = p.strip_prefix(root).unwrap_or(&p).to_string_lossy().replace('\\', "/");
        let kept = e.keep.iter().any(|k| glob_match(k, &rel));
        if !kept && e.prune.iter().any(|x| glob_match(x, &rel)) {
            crate::paths::remove_tree(&p);
        } else if p.is_dir() {
            prune(root, &p, e);
        }
    }
}

/// Byte-compiles the wheels once, with the downloaded Python: each start of a
/// Python plugin is then about 0.6 s faster. Failing here only costs speed.
fn precompile(e: &Engine, site: &Path) {
    #[cfg(windows)]
    use std::os::windows::process::CommandExt;
    let Some(py) = e.requires.iter().find_map(|r| installed_dir(r)).map(|d| d.join("python.exe")).filter(|p| p.is_file()) else { return };
    let mut cmd = std::process::Command::new(py);
    cmd.args(["-I", "-m", "compileall", "-q", "-j0"]).arg(site).stdin(std::process::Stdio::null()).stdout(std::process::Stdio::null()).stderr(std::process::Stdio::null());
    #[cfg(windows)]
    cmd.creation_flags(0x0800_0000);
    let _ = cmd.status();
}

