export function errorText(code: string | undefined, manifestErrors?: Record<string, Loc>, details?: Record<string, any> | null): string {
  if (!code) return "";
  const s = manifestErrors?.[code] ? L(manifestErrors[code]) : errors[code] ? L(errors[code]) : code;
  return fillDetails(s, details);
}

/** `{key}` from the error's details; sizes (`…Bytes`) as "1.9 MB". A placeholder with no
 * value is left out together with what leads to it (": {message}"). */
export function fillDetails(s: string, details?: Record<string, any> | null): string {
  return s
    .replace(/(\s*[:(–-]?\s*)\{(\w+)\}(\)?)/g, (_, pre: string, k: string, post: string) => {
      const v = details?.[k];
      if (v == null || v === "") return "";
      return pre + (typeof v === "number" && /bytes$/i.test(k) ? bytes(v) : String(v)) + post;
    })
    .trim();
}
